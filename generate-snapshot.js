/**
 * Tasks - V8 Snapshot & Code Cache Generator (electron-link compatible)
 * Bundles application modules into a snapshot-ready script for V8 / mksnapshot,
 * and generates V8 bytecode cache for instant compilation and execution.
 */

const path = require('path');
const fs = require('fs');
const vm = require('vm');
const crypto = require('crypto');

const ROOT_DIR = path.resolve(__dirname, '..');
const CACHE_DIR = path.join(ROOT_DIR, '.cache');
const SNAPSHOT_OUTPUT_PATH = path.join(CACHE_DIR, 'snapshot.js');
const BYTECODE_CACHE_DIR = path.join(CACHE_DIR, 'v8-code-cache');

// Ensure output directories exist
if (!fs.existsSync(CACHE_DIR)) {
  fs.mkdirSync(CACHE_DIR, { recursive: true });
}
if (!fs.existsSync(BYTECODE_CACHE_DIR)) {
  fs.mkdirSync(BYTECODE_CACHE_DIR, { recursive: true });
}

// Built-in modules & native packages to exclude from static snapshotting (handled via lazy require)
const EXCLUDED_MODULES = new Set([
  'electron',
  'electron-updater',
  'worker_threads',
  'fs',
  'path',
  'os',
  'url',
  'net',
  'http',
  'https',
  'crypto',
  'child_process',
  'stream',
  'events',
  'util',
  'assert',
  'buffer',
  'node:module'
]);

/**
 * electron-link style snapshot script generator
 * Bundles local application modules into snapshot-ready factory closures with lazy dynamic require.
 */
function generateSnapshotBundle() {
  console.log('[Snapshot] 正在执行 electron-link 架构的 V8 Snapshot 模块静态链接与打包...');

  const filesToBundle = [
    'main_worker.js',
    'sync_worker.js',
    'data_worker.js',
    'preload.js'
  ];

  const moduleDefinitions = {};

  for (const relativePath of filesToBundle) {
    const fullPath = path.join(ROOT_DIR, relativePath);
    if (!fs.existsSync(fullPath)) continue;

    const source = fs.readFileSync(fullPath, 'utf8');
    const normalizedKey = './' + relativePath.replace(/\\/g, '/');

    // Transform static requires to customRequire
    const transformedSource = source.replace(/require\s*\(\s*['"]([^'"]+)['"]\s*\)/g, (match, reqPath) => {
      const baseName = path.basename(reqPath, path.extname(reqPath));
      if (EXCLUDED_MODULES.has(baseName) || EXCLUDED_MODULES.has(reqPath)) {
        return `customRequire('${reqPath}')`;
      }
      return `customRequire('${reqPath}')`;
    });

    moduleDefinitions[normalizedKey] = transformedSource;
  }

  // Generate self-contained snapshot bundle
  const bundleScript = `/**
 * V8 Startup Snapshot Bundle
 * Generated by Tasks electron-link Snapshot Toolchain
 * Created at: ${new Date().toISOString()}
 */
(function() {
  var snapshotModules = {};
  var loadedModules = {};

  function customRequire(moduleId) {
    if (loadedModules.hasOwnProperty(moduleId)) {
      return loadedModules[moduleId].exports;
    }
    if (snapshotModules.hasOwnProperty(moduleId)) {
      var module = { exports: {}, id: moduleId };
      loadedModules[moduleId] = module;
      snapshotModules[moduleId].call(module.exports, customRequire, module.exports, module);
      return module.exports;
    }
    // Fallback to runtime Node / Electron require
    if (typeof require === 'function') {
      return require(moduleId);
    }
    throw new Error('Cannot find module "' + moduleId + '" in snapshot');
  }

  customRequire.modules = snapshotModules;
  customRequire.cache = loadedModules;

  // Register bundled snapshot modules
${Object.entries(moduleDefinitions).map(([key, code]) => {
  return `  snapshotModules[${JSON.stringify(key)}] = function(require, exports, module) {\n${code.split('\n').map(l => '    ' + l).join('\n')}\n  };`;
}).join('\n\n')}

  if (typeof globalThis !== 'undefined') {
    globalThis.__snapshotRequire__ = customRequire;
  }
  if (typeof window !== 'undefined') {
    window.__snapshotRequire__ = customRequire;
  }
  return customRequire;
})();
`;

  fs.writeFileSync(SNAPSHOT_OUTPUT_PATH, bundleScript, 'utf8');
  console.log(`[Snapshot] 成功生成 Snapshot Bundle: ${path.relative(ROOT_DIR, SNAPSHOT_OUTPUT_PATH)} (${(bundleScript.length / 1024).toFixed(2)} KB)`);

  // Verify bundle syntax in isolated VM
  try {
    new vm.Script(bundleScript, { filename: 'snapshot.js' });
    console.log('[Snapshot] Snapshot Bundle 语法及 V8 结构完整性校验通过 (PASSED)');
  } catch (err) {
    console.warn('[Snapshot] Snapshot 校验警告:', err.message);
  }

  return SNAPSHOT_OUTPUT_PATH;
}

/**
 * Generates V8 bytecode cache for critical JavaScript files
 */
function generateV8BytecodeCaches() {
  console.log('[V8 Cache] 正在生成主进程与 Worker 脚本的 V8 编译字节码缓存...');
  
  const targetFiles = [
    'main.js',
    'main_worker.js',
    'sync_worker.js',
    'data_worker.js',
    'preload.js',
    'assets/liquid-glass.js',
    'assets/card-glow.js',
    'assets/input-glow.js',
    'assets/icon-glass.js',
    'assets/switch-drag.js',
    'assets/scroll-bounce.js',
    'assets/flatpickr.min.js',
    'assets/chart.umd.min.js',
    'assets/cropper.min.js',
    'assets/fflate.min.js',
    'assets/gpu-prewarm.js',
    'assets/reduce-motion.js'
  ];

  let cachedCount = 0;
  for (const file of targetFiles) {
    const filePath = path.join(ROOT_DIR, file);
    if (!fs.existsSync(filePath)) continue;

    try {
      const code = fs.readFileSync(filePath, 'utf8');
      const script = new vm.Script(code, {
        filename: filePath,
        produceCachedData: true
      });

      const cachedData = script.createCachedData ? script.createCachedData() : script.cachedData;
      if (cachedData && cachedData.length > 0) {
        const cacheFile = path.join(BYTECODE_CACHE_DIR, `${file}.v8cache`);
        const cacheFileDir = path.dirname(cacheFile);
        if (!fs.existsSync(cacheFileDir)) {
          fs.mkdirSync(cacheFileDir, { recursive: true });
        }
        fs.writeFileSync(cacheFile, cachedData);
        cachedCount++;
        console.log(`  -> 已缓存: ${file} (${cachedData.length} 字节) -> ${path.relative(ROOT_DIR, cacheFile)}`);
      }
    } catch (err) {
      console.warn(`  x 编译缓存失败 [${file}]:`, err.message);
    }
  }

  console.log(`[V8 Cache] 编译完成，共为 ${cachedCount} 个关键脚本预热生成了 V8 代码缓存！`);
}

async function main() {
  console.log('====================================================');
  console.log('  Tasks - V8 Snapshot & Code Cache 构建优化工具');
  console.log('====================================================\n');

  try {
    generateSnapshotBundle();
  } catch (err) {
    console.warn('[Snapshot] Snapshot 构建异常:', err.message);
  }

  try {
    generateV8BytecodeCaches();
  } catch (err) {
    console.warn('[V8 Cache] V8 代码缓存生成异常:', err.message);
  }

  console.log('\n[Done] 启动优化与代码缓存构建流程完毕！');
}

main().catch((err) => {
  console.error('[Error] 构建失败:', err);
  process.exit(1);
});
